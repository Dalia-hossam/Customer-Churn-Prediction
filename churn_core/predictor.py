"""
Loads the trained pipeline + artifacts and exposes predict_one / predict_batch.
Used identically by the Streamlit app and the MCP server so behavior never
drifts between the two.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

import joblib
import pandas as pd

from .features import engineer_features, RAW_REQUIRED_COLUMNS
from .schema import CATEGORICAL_OPTIONS as _FALLBACK_CATEGORICAL_OPTIONS
from .schema import NUMERIC_RANGES as _FALLBACK_NUMERIC_RANGES

DEFAULT_MODEL_DIR = Path(__file__).resolve().parent.parent / "model"

REQUIRED_ARTIFACTS = [
    "final_model.pkl",
    "decision_threshold.pkl",
    "model_info.pkl",
    "feature_names.pkl",
]
# Optional but strongly recommended — generated by the improved training
# notebook. When present, these become the source of truth for the UI/tool
# schema and for which predict_proba column is "churn", instead of the
# hardcoded fallbacks in churn_core/schema.py.
OPTIONAL_ARTIFACTS = ["label_encoder.pkl", "input_schema.pkl"]


def _risk_level(probability: float) -> str:
    if probability >= 0.80:
        return "Very High"
    elif probability >= 0.60:
        return "High"
    elif probability >= 0.40:
        return "Medium"
    return "Low"


class ChurnPredictor:
    """Loads model artifacts once and serves predictions.

    Raises a clear, actionable error (instead of a raw stack trace) if
    `imbalanced-learn` is not installed, since the saved pipeline includes
    an ADASYN step and needs that package to unpickle even though ADASYN
    itself is skipped at inference time.
    """

    def __init__(self, model_dir: str | Path = DEFAULT_MODEL_DIR):
        self.model_dir = Path(model_dir)
        self.pipeline = self._load("final_model.pkl")
        self.threshold: float = self._load("decision_threshold.pkl")
        self.model_info: dict = self._load("model_info.pkl")
        self.feature_names: list[str] = self._load("feature_names.pkl")

        self.label_encoder = self._load_optional("label_encoder.pkl")
        self._input_schema = self._load_optional("input_schema.pkl")

        self.churn_class_index = self._resolve_churn_index()
        self.schema = self._resolve_schema()

    def _load(self, filename: str) -> Any:
        path = self.model_dir / filename
        if not path.exists():
            raise FileNotFoundError(
                f"Missing model artifact: {path}. "
                f"Make sure the model/ folder contains: {', '.join(REQUIRED_ARTIFACTS)}."
            )
        try:
            return joblib.load(path)
        except ModuleNotFoundError as e:
            raise ModuleNotFoundError(
                f"Could not load {filename}: {e}. "
                f"Install all packages in requirements.txt (this pipeline "
                f"needs imbalanced-learn to unpickle, even though ADASYN "
                f"is only used during training)."
            ) from e

    def _load_optional(self, filename: str) -> Any:
        """Like _load, but returns None instead of raising when the file is
        missing — for artifacts (label_encoder, input_schema) that older
        model/ folders may not have.
        """
        path = self.model_dir / filename
        if not path.exists():
            return None
        try:
            return joblib.load(path)
        except Exception:
            return None

    def _resolve_churn_index(self) -> int:
        """Which predict_proba() column corresponds to the "Churn" class.

        Derived from label_encoder.classes_ when available, instead of
        assuming column 1 — robust even if a future retrain encodes labels
        in a different order.
        """
        if self.label_encoder is not None and hasattr(self.label_encoder, "classes_"):
            classes = list(self.label_encoder.classes_)
            if "Yes" in classes:
                return classes.index("Yes")
        return 1  # LabelEncoder sorts alphabetically by default: No=0, Yes=1

    def _resolve_schema(self) -> dict:
        """Categorical options + numeric ranges for building UI forms / tool
        schemas. Prefers input_schema.pkl (derived from the actual training
        data) and falls back to the hardcoded defaults in churn_core/schema.py
        only if that artifact isn't present.
        """
        if self._input_schema is not None:
            return {
                "categorical_options": self._input_schema.get(
                    "categorical_options", _FALLBACK_CATEGORICAL_OPTIONS
                ),
                "numeric_ranges": self._input_schema.get(
                    "numeric_ranges", _FALLBACK_NUMERIC_RANGES
                ),
                "source": "input_schema.pkl",
            }
        return {
            "categorical_options": _FALLBACK_CATEGORICAL_OPTIONS,
            "numeric_ranges": _FALLBACK_NUMERIC_RANGES,
            "source": "churn_core/schema.py (fallback — input_schema.pkl not found)",
        }

    def _prepare(self, raw_df: pd.DataFrame) -> pd.DataFrame:
        missing = set(RAW_REQUIRED_COLUMNS) - set(raw_df.columns)
        if missing:
            raise ValueError(f"Missing required columns: {sorted(missing)}")
        return engineer_features(raw_df)

    def predict_batch(self, raw_df: pd.DataFrame) -> pd.DataFrame:
        """Predict churn for many customers at once.

        Returns a DataFrame with the original rows plus prediction columns.
        """
        prepared = self._prepare(raw_df)
        probabilities = self.pipeline.predict_proba(prepared)[:, self.churn_class_index]

        result = raw_df.copy().reset_index(drop=True)
        result["churn_probability"] = probabilities.round(4)
        result["prediction"] = [
            "Churn" if p >= self.threshold else "No Churn" for p in probabilities
        ]
        result["risk_level"] = [_risk_level(p) for p in probabilities]
        return result

    def predict_one(self, raw_record: dict) -> dict:
        """Predict churn for a single customer given as a flat dict of raw fields."""
        raw_df = pd.DataFrame([raw_record])
        result_df = self.predict_batch(raw_df)
        row = result_df.iloc[0]
        return {
            "prediction": row["prediction"],
            "churn_probability": float(row["churn_probability"]),
            "confidence": f"{row['churn_probability'] * 100:.2f}%",
            "risk_level": row["risk_level"],
            "threshold_used": self.threshold,
        }

    def summarize(self, scored_df: pd.DataFrame) -> dict:
        """Aggregate insights over a batch of already-scored customers
        (output of predict_batch), used by the dashboard and the MCP
        analyze_customers tool.
        """
        total = len(scored_df)
        churn_count = int((scored_df["prediction"] == "Churn").sum())
        risk_counts = scored_df["risk_level"].value_counts().to_dict()

        return {
            "total_customers": total,
            "predicted_churn_count": churn_count,
            "predicted_churn_rate": round(churn_count / total, 4) if total else 0.0,
            "avg_churn_probability": round(float(scored_df["churn_probability"].mean()), 4)
            if total
            else 0.0,
            "risk_level_breakdown": {
                level: int(risk_counts.get(level, 0))
                for level in ["Very High", "High", "Medium", "Low"]
            },
        }
